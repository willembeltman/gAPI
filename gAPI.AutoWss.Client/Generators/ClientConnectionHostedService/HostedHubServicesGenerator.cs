using gAPI.AutoWss.Client.Models;
using System.Linq;

namespace gAPI.AutoWss.Client.Generators.ClientConnectionHostedService;

public class HostedHubServicesGenerator : _BaseGenerator
{
    public HostedHubServicesGenerator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "HostedHubServices";
        FileName = $"Wss/{Name}.g.cs";
    }

    public Generator Context { get; }

    public override void GenerateCode()
    {
        var services = Context.ServiceContext.HubInterfaces
            .SelectMany(@interface => @interface.Services
                .Where(a => a.IsHostedHubService));

        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public record {Name}({string.Join("", services.Select(service => $@"
    {service.FullName} {service.FullName.Replace(".", "_")}"))});";
    }
}