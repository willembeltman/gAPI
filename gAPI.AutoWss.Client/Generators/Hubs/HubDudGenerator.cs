using gAPI.AutoWss.Client.Models;
using Microsoft.CodeAnalysis;
using System.Linq;

namespace gAPI.AutoWss.Client.Generators.Hubs;

public class HubDud_Generator : _BaseGenerator
{
    public HubDud_Generator(Generator context, Interface @interface)
    {
        Context = context;
        Interface = @interface;

        Namespace = "gAPI.Generated";
        Name = $"{Interface.CleanName}Dud";

        FileName = $"Hubs/{Name}.g.cs";
        Directory = "";
    }

    public Generator Context { get; }
    public Interface Interface { get; }
    public SharedReference? OwnImplementation { get; }

    public override void GenerateCode()
    {
        if (OwnImplementation != null)
        {
            Code = "";
            return;
        }

        Reg("System");
        Reg("System.Collections.Generic");
        Reg("System.Threading.Tasks");
        Reg(Interface);

        // Zorg dat alle namespaces van argumenten en return types netjes geladen worden
        foreach (var method in Interface.Methods)
        {
            RegRecursive(method.ResponseType);
            foreach (var arg in method.Arguments)
            {
                Reg(arg.ParameterType);
            }
        }

        var methodsCode = string.Join("\r\n\r\n", Interface.Methods.Select(GenerateDudMethod));

        Code = @$"
// <auto-generated />
#nullable enable
namespace {Namespace};

// Marker: HubDud Proxy Class om cross-compilatie te ondersteunen zonder netwerk-overhead
public sealed class {Name} : {Interface}
{{
{methodsCode}
}}";

        Code = $"{GetNamespacesCode()}{Code}";
    }

    private string GenerateDudMethod(InterfaceMethod method)
    {
        var parameters = string.Join(", ", method.Arguments.Select(arg =>
            arg.ParameterType.IsCancellationToken == false
                ? $"{arg.ParameterType} {arg.Name}"
                : $"{arg.ParameterType} {arg.Name} = default"));

        // Omdat de client dit nooit mag/kan aanroepen, gooien we een keiharde exception.
        // Dit is "Security by Design" op compiler-niveau.

        return $@"
    public {(method.ResponseType.IsVoid ? "void" : method.ResponseType)} {method.Name}({parameters})
    {{
        throw new NotSupportedException(""Hub broadcasting (Client-to-Client) is by design niet ondersteund op de client proxy."");
    }}";
    }
}
