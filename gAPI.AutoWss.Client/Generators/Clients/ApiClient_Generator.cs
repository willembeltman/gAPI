    private string GenerateMethodSerializer(InterfaceMethod method)
    {
        return $@"
    private byte[] ___{method}_Serializer({string.Join(", ", method.Arguments.Where(a => a.ParameterType.IsCancellationToken == false && a.ParameterType.IsIAsyncEnumerable == false).Select(arg => $@"{arg.ParameterType} {arg}"))})
