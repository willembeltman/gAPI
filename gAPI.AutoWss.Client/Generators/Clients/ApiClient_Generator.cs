    public ApiClient_Generator(Generator context, Interface @interface)
    {
        Context = context;
        Interface = @interface;

        if (context.SharedReferences.OwnApis.TryGetValue(Interface, out var impl))
        {
            OwnImplementation = impl;
            Namespace = impl.Namespace;
            Name = impl.Name;
        }
        else
        {
            Namespace = "gAPI.Generated";
            Name = @interface.CleanName;
        }

        FileName = $"Clients/{Name}.g.cs";
        Directory = "";

        PropertyHelper = new GeneratePropertyHelper([], [.. Context.CustomSpanSerializers], [], Reg, NeededSpanSerializerTypes);
    }

    public Generator Context { get; }
    public Interface Interface { get; }
    public SharedReference WssClientConnection => Context.SharedReferences.IWssClientConnection;
    public SharedReference IClientLoggerFactory => Context.SharedReferences.IClientLoggerFactory;
    public SharedReference IClientAuthenticatedHttpClient => Context.SharedReferences.IClientAuthenticatedHttpClient;
    public SharedReference CancellationTokenSourceDispose => Context.SharedReferences.CancellationTokenSourceDispose;
    public SharedReference RequestId => Context.SharedReferences.RequestId;
    public SharedReference ServiceId => Context.SharedReferences.ServiceId;
    public SharedReference RoutingDto => Context.SharedReferences.RoutingDto;
    public SharedReference IsApiProxyAttribute => Context.SharedReferences.IsApiProxyAttribute;

    public List<INamedTypeSymbol> NeededSpanSerializerTypes { get; private set; } = [];
    public GeneratePropertyHelper PropertyHelper { get; }
    public SharedReference? OwnImplementation { get; }

    public override void GenerateCode()
    {
        if (OwnImplementation != null)
        {
            Code = "";
            return;
        }

        Reg("Microsoft.Extensions.Logging");
        Reg("System");
        Reg("System.Text");
        Reg("System.Buffers.Binary");
        Reg("gAPI.Core.Attributes");
        Reg("gAPI.Core.Serializers");
        Reg(IsApiProxyAttribute);
        Reg(Interface);
        Reg(WssClientConnection);
        Reg(IClientLoggerFactory);
        Reg(IClientAuthenticatedHttpClient);
        Reg(RequestId);
        Reg(ServiceId);
        Reg(RoutingDto);
        Reg(CancellationTokenSourceDispose);
        Reg("System.Collections.Concurrent");
        Reg("System.Runtime.CompilerServices");
        Reg("System.Threading.Channels");
        Reg("Microsoft.Extensions.Logging");
        foreach (var method in Interface.Methods)
        {
            RegRecursive(method.ResponseType);
            foreach (var arg in method.Arguments)
            {
                Reg(arg.ParameterType);
            }
        }
        var generatedFunctions = string.Empty;
        var generatedFunctionNames = new HashSet<string>();

        Code = $@"
// <auto-generated />
#nullable enable
