        ___offset = 0;
        {PropertyHelper.GenerateSpanWriteCode(arg.ParameterType.UnderlayingTypes.Single().Type, "value", "        ", false)}
        return ___span.Slice(0, ___offset).ToArray();
    }}";
    }

