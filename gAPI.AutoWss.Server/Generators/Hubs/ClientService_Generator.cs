            foreach (var method in @interface.Methods)
            {
                RegRecursive(method.ResponseType);
                foreach (var arg in method.Arguments)
                {
                    if (!arg.ParameterType.IsIAsyncEnumerable)
                        RegRecursive(arg.ParameterType);
                }
            }
        }

        foreach (var @interface in Context.ServiceContext.HubInterfaces)
        {
            Reg(@interface);
            foreach (var method in @interface.Methods)
            {
                RegRecursive(method.ResponseType);
                foreach (var arg in method.Arguments)
                {
                    if (!arg.ParameterType.IsIAsyncEnumerable)
                        RegRecursive(arg.ParameterType);
                }
            }
        }
        var functions = string.Empty;
        var functionNames = new HashSet<string>();
        string argumentSerializers = GenerateArgumentSerializers();
        var methodsCode =
            string.Join("", Interface.Methods.Where(a => a.ResponseType.IsTask).Select(method => GenerateTask(method))) +
            string.Join("", Interface.Methods.Where(a => a.ResponseType.IsTask == false).Select(method => GenerateNotTask(method, ref functions, functionNames))) +
            string.Join("", Interface.Methods.Select(method => GenerateSerializer(method))) +
