    private string GenerateArgumentSerializers()
    {
        var argumentSerializers = string.Empty;
        foreach (var method in Interface.Methods)
        {
            foreach (var (arg, index) in method.Arguments.Select((arg, index) => (arg, index)))
            {
                if (!arg.ParameterType.IsIAsyncEnumerable)
                    continue;

                var innerType = arg.ParameterType.UnderlayingTypes.Single();
                argumentSerializers += $@"

    public byte[] {Interface}_{method}_{index}_Serializer({innerType} value)
    {{
        var ___offset = 0;
        {PropertyHelper.GenerateLengthCode(innerType.Type, "value", "        ", false)}
        var ___buffer = new byte[___offset];
        var ___span = new Span<byte>(___buffer);
        ___offset = 0;
        {PropertyHelper.GenerateSpanWriteCode(innerType.Type, "value", "        ", false)}
        return ___span.Slice(0, ___offset).ToArray();
    }}";
            }
        }

        return argumentSerializers;
    }

    private string GenerateDispose()
    {
        return $@"

    public void Dispose()
    {{
        ___cts.Cancel();
        ___cts.Dispose();
    }}";
    }
