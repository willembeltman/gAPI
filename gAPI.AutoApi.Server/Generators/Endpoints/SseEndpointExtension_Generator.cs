using gAPI.AutoApi.Server.Models;

namespace gAPI.AutoApi.Server.Generators.Endpoints;

public class SseEndpointExtension_Generator : BaseGenerator
{
    public SseEndpointExtension_Generator(Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "SseEndpointExtension";
        FileName = $"Endpoints\\{Name}.g.cs";
    }

    public Generator Context { get; }

    public SharedReference IServerAuthenticationService => Context.SharedReferences.IServerAuthenticationService;

    public SharedReference FabricClient => Context.SharedReferences.FabricClient;
    public SharedReference ServiceSubscriptionCollection => Context.SharedReferences.ServiceSubscriptionCollection;
    public SharedReference ServerConnectionCollection => Context.SharedReferences.ServerConnectionCollection;

    public SharedReference ServiceId => Context.SharedReferences.ServiceId;
    public SharedReference ServiceSubscriptionId => Context.SharedReferences.ServiceSubscriptionId;
    public SharedReference SseServiceSubscription => Context.SharedReferences.SseServiceSubscription;
    public SharedReference StreamingCache => Context.SharedReferences.StreamingCache;

    public override void GenerateCode()
    {
        Reg("Microsoft.AspNetCore.Mvc");
        Reg("Microsoft.AspNetCore.HttpOverrides");
        Reg("Microsoft.AspNetCore.Builder");
        Reg("Microsoft.AspNetCore.Http");
        Reg(IServerAuthenticationService);
        Reg(FabricClient);
        Reg(ServiceSubscriptionCollection);
        Reg(ServerConnectionCollection);
        Reg(ServiceId);
        Reg(SseServiceSubscription);
        Reg(ServiceSubscriptionId);
        Code = $@"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public static class {Name}
{{
    public static WebApplication MapSseEndpoint(this WebApplication app)
    {{
        // 🔥 Sse endpoint
        app.MapGet(""/SseServiceSubscription/connect/{{ids}}"", async (
            string ids,
            [FromHeader(Name = ""X-SessionId"")] string sessionId,
            [FromServices] {IServerAuthenticationService} authenticationService,
            [FromServices] {ServerConnectionCollection} serverConnectionCollection,
            [FromServices] {ServiceSubscriptionCollection} ServiceSubscriptionCollection,
            [FromServices] {StreamingCache} streamingCache,
            [FromServices] {FabricClient} fabricClient,
            CancellationToken ct
        ) =>
        {{
            var ids_split = ids.Split(new char[] {{ '_' }});
            var serviceId = ids_split[0];
            var serviceSubscriptionId = ids_split[1];

            var SseServiceSubscription = new {SseServiceSubscription}(
                authenticationService,
                serverConnectionCollection,
                ServiceSubscriptionCollection,
                streamingCache,
                fabricClient,
                new {ServiceId}(serviceId),
                new {ServiceSubscriptionId}(serviceSubscriptionId),
                authenticationService.UserId,
                authenticationService.SessionId
            );

            return Results.ServerSentEvents(
                SseServiceSubscription.ReadAllAsync(ct)
            );
        }});

        return app;
    }}
}}";
    }
}