        sp.GetRequiredService<{ApplicationDbContext}>());

    // ✅ Factory voor {AuthenticationDbContextT.FullName}<{User.FullName}>
    services.AddScoped<IDbContextFactory<{AuthenticationDbContextT.FullName}<{User.FullName}>>>(sp =>
    {{
        var factory = sp.GetRequiredService<IDbContextFactory<{ApplicationDbContext}>>();

        return new AuthenticationDbContextFactory<{AuthenticationDbContextT.FullName}<{User.FullName}>>(
            () => factory.CreateDbContext());
    }});")}
    return services;
}}
}}
";
    }
