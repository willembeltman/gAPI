                    sp.GetRequiredService<IDbContextFactory<{AuthenticationDbContextT.FullName}<{User.FullName}>>>(),
                    sp.GetRequiredService<TimeProvider>(),
                    loginMaxAttempt, 
                    loginMaxAttemptTimeout,
                    registerMaxAttempt,
                    registerMaxAttemptTimeout,
                    forgetPasswordMaxAttempt,
                    forgetPasswordMaxAttemptTimeout,
                    changePasswordMaxAttempt,
                    changePasswordMaxAttemptTimeout));

            services.AddScoped<{IAuthenticationStateFactoryT}<{User.FullName}>>(sp => 
                new {AuthenticationStateFactoryT}<{User.FullName}>(
                    sp.GetRequiredService<IDbContextFactory<{AuthenticationDbContextT.FullName}<{User.FullName}>>>(),
                    sp.GetRequiredService<TimeProvider>(),
                    shortHoursAgo,
                    longHoursAgo,
                    useMemoryDatabase));

            services.AddScoped<{IUserTokenFactoryT.FullName}<{User.FullName}>, {UserTokenFactoryT}<{User.FullName}>>();
            services.AddScoped<{IAccountService.FullName}, {AccountServiceT.FullName}<{User.FullName}, {State.FullName}>>();

            services.AddDatabase(useMemoryDatabase, dbConnectionString);
        }}
