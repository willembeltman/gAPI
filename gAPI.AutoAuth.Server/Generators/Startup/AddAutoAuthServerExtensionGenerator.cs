    public SharedReference IAccountService => Context.SharedReferences.IAccountService;
    public SharedReference IAuthenticationSecurity => Context.SharedReferences.IAuthenticationSecurity;
    public SharedReference AuthenticationHandler => Context.SharedReferences.AuthenticationHandler;
    public SharedReference IServerAuthenticationService => Context.SharedReferences.IServerAuthenticationService;
    public SharedReference NoDbAuthenticationService => Context.NoDbAuthenticationService;
    public SharedReference IStateParser => Context.IStateParser;
    public SharedReference StateParser => Context.StateParser;
    public SharedReference IStateParserT => Context.SharedReferences.IStateParserT;
    public SharedReference AuthenticationMiddleware => Context.SharedReferences.AuthenticationMiddleware;
    public SharedReference AuthenticationOptions => Context.SharedReferences.AuthenticationOptions;

    public override void GenerateCode()
    {
        Reg(AuthenticationStateMappingT);
        Reg(AuthenticationStateFactoryT);
        Reg(IUserTokenFactoryT);
        Reg(UserTokenFactoryT);
        Reg(AuthenticationSecurityT);
        Reg(IAuthenticationStateFactoryT);
        Reg(IAccountService);
        Reg(IAuthenticationSecurity);
        Reg(AuthenticationHandler);
        Reg(IServerAuthenticationService);
        Reg(NoDbAuthenticationService);
        Reg(IStateMappingT);
        Reg(AuthenticationDbContextT);
        Reg(ServerConfig);
        Reg(IStateParserT);
        Reg(IStateParser);
        Reg(StateParser);
        Reg(AuthenticationMiddleware);
        Reg(AuthenticationOptions);
        if (CustomStateMapping != null)
            Reg(CustomStateMapping);

        Reg(State);
        Reg(User);
        Reg("Microsoft.EntityFrameworkCore");
        Reg("Microsoft.AspNetCore.Authentication");
        Reg("Microsoft.Extensions.Configuration");
        Reg("gAPI.Core.Server.Extensions");
        Reg("Microsoft.Extensions.Hosting");
        Reg("Microsoft.Extensions.DependencyInjection");

        Code = $@"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public static class {Name}
{{
    public static IServiceCollection AddAutoAuthServer(
        this IServiceCollection services,
        IConfigurationManager configuration)
    {{
        var serverConfig = configuration.CreateServerConfig();
        return AddAutoAuthServer(services, serverConfig);
    }}
    public static IServiceCollection AddAutoAuthServer(
        this IServiceCollection services, 
        {ServerConfig.FullName} serverConfig)
    {{
        return AddAutoAuthServer(
            services, 
            serverConfig.UseMemoryDatabase, 
            serverConfig.DefaultConnectionString, 
            serverConfig.LoginMaxAttempt, 
            serverConfig.LoginMaxAttemptTimeout, 
            serverConfig.RegisterMaxAttempt, 
            serverConfig.RegisterMaxAttemptTimeout, 
            serverConfig.ForgetPasswordMaxAttempt, 
            serverConfig.ForgetPasswordMaxAttemptTimeout, 
            serverConfig.ChangePasswordMaxAttempt, 
            serverConfig.ChangePasswordMaxAttemptTimeout);
    }}

    public static IServiceCollection AddAutoAuthServer(
        this IServiceCollection services,
        bool useMemoryDatabase = false,
        string? dbConnectionString = null,
        int loginMaxAttempt = 5,
        long loginMaxAttemptTimeout = 15,
        int registerMaxAttempt = 5,
        long registerMaxAttemptTimeout = 24 * 7 * 52, // 8736
        int forgetPasswordMaxAttempt = 5,
        long forgetPasswordMaxAttemptTimeout = 24,
        int changePasswordMaxAttempt = 5,
        long changePasswordMaxAttemptTimeout = 24,
        double shortHoursAgo = -1,
        double longHoursAgo = -72)
    {{
        services.AddSingleton(new {AuthenticationOptions.FullName}(true)); // TODO

        if (dbConnectionString == null)
        {{
            services.AddScoped<{NoDbAuthenticationService.FullName}>();
            services.AddScoped<{IAuthenticationService.FullName}>(sp => sp.GetRequiredService<{NoDbAuthenticationService.FullName}>());
        }}
        else
        {{
            services.AddScoped<{AuthenticationService.FullName}>();
            services.AddScoped<{IAuthenticationService.FullName}>(sp => sp.GetRequiredService<{AuthenticationService.FullName}>());

            services.AddScoped<{IAuthenticationSecurity.FullName}>(sp => 
                new {AuthenticationSecurityT.FullName}<{User.FullName}, {State.FullName}>(
