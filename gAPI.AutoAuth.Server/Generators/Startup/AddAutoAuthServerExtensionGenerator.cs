                .AddScheme<AuthenticationSchemeOptions, {AuthenticationHandler.FullName}>(""gAPI"", _ => {{ }});

        services.AddScoped<{IAuthenticationServiceT.FullName}<{User.FullName}, {State.FullName}>>(sp => sp.GetRequiredService<{IAuthenticationService.FullName}>());
