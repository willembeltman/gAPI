using System.Linq;

namespace gAPI.AutoBus.Generators.BusContext;

public class IBusContext_Generator : _BaseGenerator
{
    public IBusContext_Generator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "IBusContext";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }

    public override void GenerateCode()
    {
        foreach (var a in Context.ClientContexts)
        {
            Reg(a);
            Reg(a.IClientContext);
        }
        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name}
{{{string.Join("", Context.ClientContexts.Select(a => $@"    
    public {a.IClientContext.Name} {a.Client.Interface.CleanName} {{ get; }}"))}
}}";
    }
}