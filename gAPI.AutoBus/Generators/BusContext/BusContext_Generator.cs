using gAPI.AutoBus.Helpers;
using System.Linq;

namespace gAPI.AutoBus.Generators.BusContext;

public class BusContext_Generator : _BaseGenerator
{
    public BusContext_Generator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "BusContext";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }

    public IBusContext_Generator IBusContext => Context.IBusContext;

    public override void GenerateCode()
    {
        Reg(IBusContext);
        foreach (var a in Context.ClientContexts)
        {
            Reg(a);
            Reg(a.IClientContext);
        }
        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public class {Name}({string.Join(",", Context.ClientContexts.Select(a => $@"    
    {a.IClientContext.Name} {a.Client.Interface.CleanName.ToCamelCase()}"))})
    : {IBusContext.Name}
{{{string.Join("", Context.ClientContexts.Select(a => $@"    
    public {a.IClientContext.Name} {a.Client.Interface.CleanName} {{ get; }} = {a.Client.Interface.CleanName.ToCamelCase()};"))}
}}";
    }
}