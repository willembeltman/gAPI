using gAPI.AutoBus.Generators.BusClient;
using gAPI.AutoBus.Models;

namespace gAPI.AutoBus.Generators.BusClientContext;

public class IBusClientContext_Generator : _BaseGenerator
{
    public IBusClientContext_Generator(
        Generator context,
        BusClient_Generator clientHandler)
    {
        Context = context;
        ClientHandler = clientHandler;

        Directory = "";
        Namespace = clientHandler.Namespace;

        Name = "I" + ClientHandler.Interface.CleanName + "Context";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }
    public BusClient_Generator ClientHandler { get; }
    public Interface IClientHandler => ClientHandler.Interface;

    public override void GenerateCode()
    {
        Reg(IClientHandler);
        Reg(ClientHandler);
        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name}
{{
    {IClientHandler.Name} ToAll {{ get; }}
    {IClientHandler.Name} ToAny {{ get; }}
}}";
    }
}