using gAPI.AutoBus.Generators.BusClient;
using gAPI.AutoBus.Models;

namespace gAPI.AutoBus.Generators.BusClientContext;

public class BusClientContext_Generator : _BaseGenerator
{
    public BusClientContext_Generator(
        Generator context,
        IBusClientContext_Generator iClientHandlerContext)
    {
        Context = context;
        IClientContext = iClientHandlerContext;

        Namespace = iClientHandlerContext.Namespace;
        Name = Client.Interface.CleanName + "Context";

        Directory = "";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }
    public IBusClientContext_Generator IClientContext { get; }
    public SharedReference BusChoiceType => Context.SharedReferences.BusToChoice;
    public SharedReference BusConnectionId => Context.SharedReferences.BusConnectionId;

    public SharedReference DeliveryMode => Context.SharedReferences.DeliveryMode;
    public SharedReference IBusConnection => Context.IBusConnection;
    public BusClient_Generator Client => IClientContext.ClientHandler;
    public Interface IClient => Client.Interface;

    public override void GenerateCode()
    {
        Reg(IClientContext);
        Reg(IClient);
        Reg(Client);
        Reg(IBusConnection);
        Reg(BusChoiceType);
        Reg(BusConnectionId);
        Reg(DeliveryMode);
        Reg("System");
        Reg("Microsoft.Extensions.Logging");
        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public class {Name}(
    ILoggerFactory loggerFactory,
    {IBusConnection} busConnection)
    : {IClientContext}
{{
    public {IClient} ToAll(TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient)
        => new {Client}(loggerFactory, busConnection, timeOut, deliveryMode, {BusChoiceType}.ToAll);
    public {IClient} ToAny(TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient)
        => new {Client}(loggerFactory, busConnection, timeOut, deliveryMode, {BusChoiceType}.ToAny);
    public {IClient} ToBusConnectionId({BusConnectionId} busConnectionId, TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient)
        => new {Client}(loggerFactory, busConnection, timeOut, deliveryMode, {BusChoiceType}.ToBusConnectionId, busConnectionId);
}}";
    }
}