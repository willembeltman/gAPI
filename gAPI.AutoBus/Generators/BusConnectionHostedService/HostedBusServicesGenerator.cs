using gAPI.AutoBus.Models;
using System.Linq;

namespace gAPI.AutoBus.Generators.BusConnectionHostedService;

public class HostedBusServicesGenerator : _BaseGenerator
{
    public HostedBusServicesGenerator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "HostedBusServices";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }

    public override void GenerateCode()
    {
        var services = Context.ServiceContext.BusInterfaces
            .SelectMany(@interface => @interface.Services
                .Where(a => a.IsHostedBusService));

        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public record {Name}({string.Join("", services.Select(service => $@"
    {service.FullName} {service.FullName.Replace(".", "_")}"))});";
    }
}