using gAPI.AutoBus.Models;
using System.Linq;

namespace gAPI.AutoBus.Generators.BusConnection;

public class IBusConnectionGenerator : _BaseGenerator
{
    public IBusConnectionGenerator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "IBusConnection";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }
    public SharedReference IBaseBusConnection => Context.SharedReferences.IBaseBusConnection;

    public override void GenerateCode()
    {
        Reg(IBaseBusConnection);
        foreach (var @interface in Context.ServiceContext.BusInterfaces)
        {
            foreach (var service in @interface.Services)
            {
                Reg(service);
            }
            Reg(@interface);
        }

        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name} : {IBaseBusConnection}
{{

    Task SubscribeAsync(object implementation, CancellationToken ___ct = default);
    Task UnsubscribeAsync(object implementation, CancellationToken ___ct = default);

    {string.Join("", Context.ServiceContext.BusInterfaces.Select(@interface => string.Join("", @interface.Services.Select(service => $@"
    {service}? {service} {{ get; set; }}"))))}
}}";
    }
}