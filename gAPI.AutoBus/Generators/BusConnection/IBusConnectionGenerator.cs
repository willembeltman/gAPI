using gAPI.AutoBus.Models;
using System.Linq;

namespace gAPI.AutoBus.Generators.BusConnection;

public class IBusConnectionGenerator : _BaseGenerator
{
    public IBusConnectionGenerator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "IBusConnection";
        FileName = $"Bus/{Name}.g.cs";
    }

    public Generator Context { get; }
    public SharedReference IBaseBusConnection => Context.SharedReferences.IBaseBusConnection;
    public SharedReference HostedBusServices => Context.HostedBusServices;

    public override void GenerateCode()
    {
        Reg(IBaseBusConnection);
        Reg(HostedBusServices);

        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name} : {IBaseBusConnection}
{{
    Task SubscribeAsync(object implementation, CancellationToken ct = default);
    Task UnsubscribeAsync(object implementation, CancellationToken ct = default);

    Task OnSubscribedAsync(object implementation, CancellationToken ct);
    Task OnUnsubscribedAsync(object implementation, CancellationToken ct);

    {HostedBusServices}? HostedBusServices {{ get; set; }}
}}";
    }
}