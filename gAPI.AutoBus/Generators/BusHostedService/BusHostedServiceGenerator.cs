using gAPI.AutoBus.Helpers;
using gAPI.AutoBus.Models;
using gAPI.AutoSerializer;
using Microsoft.CodeAnalysis;
using System.Collections.Generic;
using System.Linq;

namespace gAPI.AutoBus.Generators.BusHostedService;

public class BusHostedServiceGenerator : _BaseGenerator
{
    public BusHostedServiceGenerator(Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "BusHostedService";
        FileName = $"Bus/{Name}.g.cs";

        PropertyHelper = new GeneratePropertyHelper([], [.. Context.CustomSpanSerializers], [], Reg, NeededSpanSerializers);
    }

    public Generator Context { get; }

    public SharedReference IBusConnection => Context.IBusConnection;
    public SharedReference ServiceBusConfig => Context.SharedReferences.ServiceBusConfig;
    public SharedReference BusInvokeRequestDto => Context.SharedReferences.BusInvokeRequestDto;
    public SharedReference BusSendRequestDto => Context.SharedReferences.BusSendRequestDto;
    public SharedReference ServiceId => Context.SharedReferences.ServiceId;
    public SharedReference StreamingResponseDto => Context.SharedReferences.StreamingResponseDto;
    public SharedReference? FabricClient => Context.SharedReferences.FabricClient;

    public List<INamedTypeSymbol> NeededSpanSerializers { get; private set; } = [];
    public GeneratePropertyHelper PropertyHelper { get; }

    public override void GenerateCode()
    {

        Reg("Microsoft.Extensions.DependencyInjection");
        Reg("Microsoft.Extensions.Hosting");
        Reg("System");
        Reg(IBusConnection);

        foreach (var item in Context.ServiceContext.BusInterfaces.SelectMany(a => a.Services))
        {
            Reg(item);
        }

        Code = @$"
// <auto-generated />
#nullable enable
namespace {Namespace};

public class {Name}(
    {IBusConnection} busConnection,
    IServiceProvider serviceProvider)
    : IHostedService
{{
    private AsyncServiceScope? Scope;

    public async Task StartAsync(CancellationToken ct)
    {{
        if (Scope != null)
            return;

        Scope = serviceProvider.CreateAsyncScope();
        {string.Join("", Context.ServiceContext.BusInterfaces.Select(@interface => string.Join("", @interface.Services.Select(service => $@"
        busConnection.{service} = Scope.Value.ServiceProvider.GetRequiredService<{service}>();
        await busConnection.SubscribeAsync(busConnection.{service}, ct);"))))}
    }}

    public async Task StopAsync(CancellationToken ct)
    {{
        if (Scope == null)
            return;

        {string.Join("", Context.ServiceContext.BusInterfaces.Select(@interface => string.Join("", @interface.Services.Select(service => $@"
        await busConnection.UnsubscribeAsync(busConnection.{service}, ct);
        busConnection.{service} = null;"))))}

        await Scope.Value.DisposeAsync();
        Scope = null;
    }}
}}

";
        Code = $"{GetNamespacesCode()}{Code}";
    }

}