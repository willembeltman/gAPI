using gAPI.AutoBus.Generators.BusClientContext;
using gAPI.AutoBus.Generators.BusContext;
using gAPI.AutoBus.Models;
using System.Linq;

namespace gAPI.AutoBus.Generators.Startup;

public class AddAutoBusExtensionGenerator : _BaseGenerator
{
    public AddAutoBusExtensionGenerator(
        Generator context)
    {
        Context = context;

        Name = "AddAutoBusExtension";
        Namespace = "gAPI.Generated";

        Directory = "";
        FileName = $"Startup/{Name}.g.cs";
    }

    public Generator Context { get; }

    public BusClientContext_Generator[] ClientContexts => Context.ClientContexts;
    public IBusContext_Generator IClientContext => Context.IBusContext;
    public BusContext_Generator ClientContext => Context.BusContext;
    public SharedReference IBusConnection => Context.IBusConnection;
    public SharedReference BusConnection => Context.BusConnection;

    public SharedReference ServiceBusConfig => Context.SharedReferences.ServiceBusConfig;

    public override void GenerateCode()
    {
        Reg(IClientContext);
        Reg(ClientContext);
        Reg(ServiceBusConfig);
        Reg("gAPI.Core.Server.Extensions");
        Reg("System.Net");
        Reg("Microsoft.Extensions.Primitives");
        Reg("Microsoft.Extensions.DependencyInjection");
        Reg("Microsoft.Extensions.Logging");
        Reg("Microsoft.Extensions.Hosting");
        Reg("Microsoft.Extensions.Configuration");


        foreach (var clientHandlerContext in ClientContexts)
        {
            Reg(clientHandlerContext);
            Reg(clientHandlerContext.IClientContext);
        }

        foreach (var @interface in Context.ServiceContext.BusInterfaces)
        {
            Reg(@interface);
            foreach (var method in @interface.Methods)
            {
                RegRecursive(method.ResponseType);
                foreach (var arg in method.Arguments)
                {
                    Reg(arg.ParameterType);
                }
            }
        }

        Reg("Microsoft.Extensions.DependencyInjection.Extensions");
        var fabricClientCode = "";
        if (Context.SharedReferences.BaseFabricConnection != null && Context.SharedReferences.FabricClient != null)
        {
            Reg(Context.SharedReferences.FabricClient);
            if (Context.SharedReferences.FabricClient != null) Reg(Context.SharedReferences.FabricClient);
            if (Context.SharedReferences.SessionCache != null) Reg(Context.SharedReferences.SessionCache);
            if (Context.SharedReferences.StreamingCache != null) Reg(Context.SharedReferences.StreamingCache);
            if (Context.SharedReferences.ServiceSubscriptionCollection != null) Reg(Context.SharedReferences.ServiceSubscriptionCollection);

            if (Context.SharedReferences.FabricClient != null)
            {
                fabricClientCode = $@"
        // Fabric Client
        services.TryAddSingleton<{Context.SharedReferences.FabricClient}>(sp =>
        {{
            var sessionCache = new {Context.SharedReferences.SessionCache}();
            var streamingCache = new {Context.SharedReferences.StreamingCache}();
            var busConnections = new {Context.SharedReferences.BusConnectionCollection}();
            var loggerFactory = sp.GetRequiredService<ILoggerFactory>();
            return new {Context.SharedReferences.FabricClient}(
                sessionCache, streamingCache, busConnections, loggerFactory, config.ConnectionString);
        }});";
            }
        }

        Code = $@"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public static class {Name}
{{
    public static IServiceCollection AddAutoBus(
        this IServiceCollection services,
        IConfigurationManager configuration,
        TimeProvider? dateTime = null)
    {{
        var config = configuration.CreateBusConfig();
        return AddAutoBus(
            services, 
            config,
            dateTime);
    }}

    public static IServiceCollection AddAutoBus(
        this IServiceCollection services, 
        {ServiceBusConfig} config,
        TimeProvider? dateTime = null)
    {{
        services.AddSingleton(config);
        services.AddSingleton(dateTime ?? TimeProvider.System);
{fabricClientCode}

        // Connection
        services.AddSingleton<{IBusConnection}, {BusConnection}>();

        // Hubs
        services.AddScoped<{IClientContext}, {ClientContext}>();{string.Join("", ClientContexts.Select(a => $@"
        services.AddScoped<{a.IClientContext.Name}, {a.Name}>();"))}

        return services;
    }}
}}";

    }
}