        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "IClientConnection";
        FileName = $"Sse/{Name}.g.cs";
    }

    public Generator Context { get; }
    public SharedReference ISseClientConnection => Context.SharedReferences.ISseClientConnection;
    public SharedReference HostedHubServices => Context.HostedHubServices;

    public override void GenerateCode()
    {
        Reg(ISseClientConnection);
        Reg(HostedHubServices);

        Code = @$"// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name} : {ISseClientConnection}
{{
    {HostedHubServices}? HostedHubServices {{ get; set; }}
}}";
        Code = $"{GetNamespacesCode()}{Code}";
    }
}