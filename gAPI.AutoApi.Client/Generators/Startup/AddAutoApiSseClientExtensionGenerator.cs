using gAPI.AutoApi.Client.Generators.Clients;
using gAPI.AutoApi.Client.Models;
using System.Linq;

namespace gAPI.AutoApi.Client.Generators.Startup;

public class AddAutoApiClientExtensionGenerator : _BaseGenerator
{
    public AddAutoApiClientExtensionGenerator(Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "AutoApiSseClientExtension";
        FileName = $"Startup/{Name}.g.cs";
    }

    public Generator Context { get; }
    public ApiClientGenerator[] Clients => Context.Clients;
    public SharedReference ClientConnectionHostedService => Context.ClientConnectionHostedService;
    public SharedReference ClientConnection => Context.ClientConnection;
    public SharedReference IClientConnection => Context.IClientConnection;
    public SharedReference ISseClientConnection => Context.SharedReferences.ISseClientConnection;
    public SharedReference SseManagerCollection => Context.SharedReferences.SseManagerCollection;
    public SharedReference ClientConfig => Context.SharedReferences.ClientConfig;

    public SharedReference IUriNavigationManager => Context.SharedReferences.IUriNavigationManager;
    public SharedReference DefaultNavigationManager => Context.SharedReferences.DefaultNavigationManager;
    public SharedReference StaticNavigationManager => Context.SharedReferences.StaticNavigationManager;
    public SharedReference WithCookiesHandler => Context.SharedReferences.WithCookiesHandler;


    //public SharedReference? IClientAuthenticatedHttpClientImplementation => Context.SharedReferences.IClientAuthenticatedHttpClientImplementation;
    //public SharedReference AuthenticatedHttpClient => Context.AuthenticatedHttpClient;
    //public SharedReference IAuthenticatedHttpClient => Context.IAuthenticatedHttpClient;

    public override void GenerateCode()
    {
        Reg("Microsoft.Extensions.DependencyInjection");
        Reg("Microsoft.Extensions.DependencyInjection.Extensions");
        Reg("Microsoft.AspNetCore.Components");
        Reg("Microsoft.AspNetCore.Components.Authorization");
        Reg("Microsoft.Extensions.Configuration");
        Reg("gAPI.Core.Client.Extensions");
        Reg(ClientConfig);
        Reg(ClientConnection);
        Reg(ISseClientConnection);
        Reg(SseManagerCollection);
        Reg(DefaultNavigationManager);
        Reg(StaticNavigationManager);
        Reg(WithCookiesHandler);
        Reg(ClientConnectionHostedService);

        foreach (var @interface in Context.ServiceContext.HubInterfaces)
        {
            foreach (var service in @interface.Services)
            {
                if (service.IsHostedHubService)
                    Reg(service);
            }
        }

        var propertiesCode = "";
        foreach (var client in Clients)
        {
            var @interface = client.Interface;
            Reg(@interface);
            Reg(client);
            propertiesCode += $"\r\n        services.AddScoped<{@interface.Name}, {client.Name}>();";
        }

        Code = $@"{GetNamespacesCode()}
// <auto-generated />
namespace {Namespace};

public static class {Name}
{{
    public static IServiceCollection AddAutoApiClient(
        this IServiceCollection services,
        IConfigurationManager configuration)
    {{
        var config = configuration.CreateClientConfig();
        return AddAutoApiClient(services, config);
    }}

    public static IServiceCollection AddAutoApiClient(this IServiceCollection services, {ClientConfig} clientConfig)
    {{{propertiesCode}
        services.AddSingleton(clientConfig);
        services.AddScoped<{ClientConnection}>();
        services.AddScoped<{IClientConnection}>(sp => sp.GetRequiredService<{ClientConnection}>());
        services.AddScoped<{ISseClientConnection}>(sp => sp.GetRequiredService<{ClientConnection}>());

        var sseManagerCollection = new {SseManagerCollection}();
        services.AddSingleton(sseManagerCollection);
        {string.Join("", Context.ServiceContext.HubInterfaces.Select(@interface => string.Join("", @interface.Services.Where(a => a.IsHostedHubService).Select(service => $@"
        services.AddSingleton<{service}>();"))))}
        services.AddHostedService<{ClientConnectionHostedService}>();

        // Het kan helaas niet anders
        services.AddScoped<{IUriNavigationManager}>(sp =>
        {{
            var navigationManager = sp.GetService<NavigationManager>();
            if (navigationManager != null)
            {{
                return new {DefaultNavigationManager}(navigationManager);
            }}
            else
            {{
                return new {StaticNavigationManager}();
            }}
        }});

        // Register the cookie handler
        services.AddSingleton<{WithCookiesHandler}>();

        return services;
    }}
}}";
    }
}