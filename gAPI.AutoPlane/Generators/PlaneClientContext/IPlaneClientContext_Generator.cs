using gAPI.AutoPlane.Generators.PlaneClient;
using gAPI.AutoPlane.Models;

namespace gAPI.AutoPlane.Generators.PlaneClientContext;

public class IPlaneClientContext_Generator : _BaseGenerator
{
    public IPlaneClientContext_Generator(
        Generator context,
        PlaneClient_Generator clientHandler)
    {
        Context = context;
        ClientHandler = clientHandler;

        Directory = "";
        Namespace = clientHandler.Namespace;

        Name = "I" + ClientHandler.Interface.CleanName + "Context";
        FileName = $"Plane/{Name}.g.cs";
    }

    public Generator Context { get; }
    public PlaneClient_Generator ClientHandler { get; }
    public Interface Interface => ClientHandler.Interface;
    public SharedReference DeliveryMode => Context.SharedReferences.DeliveryMode;
    public SharedReference PlaneConnectionId => Context.SharedReferences.PlaneConnectionId;

    public override void GenerateCode()
    {
        Reg(Interface);
        Reg(ClientHandler);
        Reg(DeliveryMode);
        Reg(PlaneConnectionId);
        Reg("System");
        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public interface {Name}
{{
    {Interface.Name} ToAll(TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient, bool throwIfNoReceiver = true);
    {Interface.Name} ToAny(TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient);
    {Interface.Name} ToPlaneConnectionId({PlaneConnectionId} planeConnectionId, TimeSpan? timeOut = null, {DeliveryMode} deliveryMode = DeliveryMode.Transient);
}}";
    }
}