using gAPI.AutoPlane.Models;
using System.Linq;

namespace gAPI.AutoPlane.Generators.PlaneConnectionHostedService;

public class HostedPlaneServicesGenerator : _BaseGenerator
{
    public HostedPlaneServicesGenerator(
        Generator context)
    {
        Context = context;

        Directory = "";
        Namespace = "gAPI.Generated";

        Name = "HostedPlaneServices";
        FileName = $"Plane/{Name}.g.cs";
    }

    public Generator Context { get; }

    public override void GenerateCode()
    {
        var services = Context.ServiceContext.PlaneInterfaces
            .SelectMany(@interface => @interface.Services
                .Where(a => a.IsHostedPlaneService));

        Code = @$"{GetNamespacesCode()}
// <auto-generated />
#nullable enable
namespace {Namespace};

public record {Name}({string.Join(",", services.Select(service => $@"
    {service.FullName} {service.FullName.Replace(".", "_")}"))});";
    }
}